CREATE TABLE IF NOT EXISTS contest_leaderboard_snapshot (
    contest_id BIGINT NOT NULL,
    user_id BIGINT NOT NULL,
    display_name VARCHAR(255) NOT NULL,
    college VARCHAR(255) NULL,
    solved INT NOT NULL DEFAULT 0,
    total_points INT NOT NULL DEFAULT 0,
    first_accepted_at DATETIME NULL,
    rank_position INT NOT NULL,
    snapshot_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (contest_id, user_id),
    KEY idx_cls_contest_rank (contest_id, rank_position),
    KEY idx_cls_snapshot_at (snapshot_at),
    KEY idx_cls_contest_snapshot (contest_id, snapshot_at)
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS contest_first_solver_snapshot (
    contest_id BIGINT NOT NULL,
    problem_id BIGINT NOT NULL,
    problem_title VARCHAR(255) NOT NULL,
    first_solver_user_id BIGINT NULL,
    first_solver_name VARCHAR(255) NULL,
    first_solved_at DATETIME NULL,
    snapshot_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (contest_id, problem_id),
    KEY idx_cfss_snapshot_at (snapshot_at),
    KEY idx_cfss_contest_snapshot (contest_id, snapshot_at),
    KEY idx_cfss_solver (first_solver_user_id)
) ENGINE=InnoDB;

