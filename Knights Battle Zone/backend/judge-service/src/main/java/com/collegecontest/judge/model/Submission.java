package com.collegecontest.judge.model;

import jakarta.persistence.Column;
import jakarta.persistence.Entity;
import jakarta.persistence.Id;
import jakarta.persistence.Lob;
import jakarta.persistence.Table;
import java.time.Instant;

@Entity
@Table(name = "judge_submissions")
public class Submission {
    @Id
    private String id;

    private String language;
    @Column(name = "problem_id")
    private Long problemId;

    @Lob
    @Column(length = 16_777_215)
    private String code;

    @Column(name = "time_limit_seconds")
    private Integer timeLimitSeconds;

    @Column(name = "memory_mb")
    private Integer memoryMb;

    private Double cpus;

    private String status; // PENDING, RUNNING, ACCEPTED, TIME_LIMIT, RUNTIME_ERROR, ERROR

    private Integer exitCode;

    @Lob
    @Column(length = 16_777_215)
    private String stdout;

    @Lob
    @Column(length = 16_777_215)
    private String stderr;

    @Lob
    @Column(length = 16_777_215)
    private String details; // JSON details of per-test results (only non-hidden tests)

    private Double runtimeSeconds;

    private Long peakMemoryBytes;

    private Instant createdAt;

    private Instant updatedAt;

    public Submission() {
    }

    // getters/setters generated by IDE or Lombok not used to keep plain java
    public String getId() {
        return id;
    }

    public void setId(String id) {
        this.id = id;
    }

    public String getLanguage() {
        return language;
    }

    public void setLanguage(String language) {
        this.language = language;
    }

    public String getCode() {
        return code;
    }

    public void setCode(String code) {
        this.code = code;
    }

    public Integer getTimeLimitSeconds() {
        return timeLimitSeconds;
    }

    public void setTimeLimitSeconds(Integer timeLimitSeconds) {
        this.timeLimitSeconds = timeLimitSeconds;
    }

    public Integer getMemoryMb() {
        return memoryMb;
    }

    public void setMemoryMb(Integer memoryMb) {
        this.memoryMb = memoryMb;
    }

    public Double getCpus() {
        return cpus;
    }

    public void setCpus(Double cpus) {
        this.cpus = cpus;
    }

    public Long getProblemId() {
        return problemId;
    }

    public void setProblemId(Long problemId) {
        this.problemId = problemId;
    }

    public String getDetails() {
        return details;
    }

    public void setDetails(String details) {
        this.details = details;
    }

    public String getStatus() {
        return status;
    }

    public void setStatus(String status) {
        this.status = status;
    }

    public Integer getExitCode() {
        return exitCode;
    }

    public void setExitCode(Integer exitCode) {
        this.exitCode = exitCode;
    }

    public String getStdout() {
        return stdout;
    }

    public void setStdout(String stdout) {
        this.stdout = stdout;
    }

    public String getStderr() {
        return stderr;
    }

    public void setStderr(String stderr) {
        this.stderr = stderr;
    }

    public Double getRuntimeSeconds() {
        return runtimeSeconds;
    }

    public void setRuntimeSeconds(Double runtimeSeconds) {
        this.runtimeSeconds = runtimeSeconds;
    }

    public Long getPeakMemoryBytes() {
        return peakMemoryBytes;
    }

    public void setPeakMemoryBytes(Long peakMemoryBytes) {
        this.peakMemoryBytes = peakMemoryBytes;
    }

    public Instant getCreatedAt() {
        return createdAt;
    }

    public void setCreatedAt(Instant createdAt) {
        this.createdAt = createdAt;
    }

    public Instant getUpdatedAt() {
        return updatedAt;
    }

    public void setUpdatedAt(Instant updatedAt) {
        this.updatedAt = updatedAt;
    }
}
